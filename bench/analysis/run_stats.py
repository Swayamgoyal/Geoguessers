"""Median and IQR of every measured configuration (the plan's reporting rule: median and IQR, docs/PROJECT_PLAN.md
§6.2). Writes results/run_stats.csv (every configuration) and results/run_stats.md (summary + widest spreads).

Measured repeats only (rep >= 1, ok runs). IQR = 75th - 25th percentile of t_total (process wall time); for the
QGIS test (E1q) and the read reference the timed quantity is t_internal, as in the result tables. E5 timings
(in-process, results/e5_timing.csv) are summarised over the 8 tile positions / 3 whole-grid repeats.

    python -m bench.analysis.run_stats
"""
import numpy as np
import pandas as pd

from bench.analysis.phase2_report import RES, md_table

KEYS = ["experiment", "dataset", "variant", "op", "method", "impl", "cache_state"]


def timed(d):
    t = pd.to_numeric(d.t_internal, errors="coerce")
    use_internal = (d.experiment == "E1q") | (d.op == "read")
    return np.where(use_internal & t.notna(), t, d.t_total)


def summarise(g, col):
    q1, med, q3 = g[col].quantile([0.25, 0.5, 0.75])
    return pd.Series({"n": len(g), "median_s": med, "q1_s": q1, "q3_s": q3, "iqr_s": q3 - q1,
                      "iqr_pct": 100 * (q3 - q1) / med if med else np.nan, "min_s": g[col].min(), "max_s": g[col].max()})


def main():
    d = pd.read_csv(RES / "runs.csv")
    d = d[d.ok & (d.rep >= 1)].copy()
    for k in KEYS:
        d[k] = d[k].fillna("")
    d["timed_s"] = timed(d)
    runs = d.groupby(KEYS, sort=False).apply(summarise, "timed_s", include_groups=False).reset_index()
    runs = runs[runs.n >= 3]
    e5 = pd.read_csv(RES / "e5_timing.csv") if (RES / "e5_timing.csv").exists() else pd.DataFrame()
    if len(e5):
        e5 = (e5.groupby(["dataset", "view", "level", "route", "cache"], sort=False)
              .apply(summarise, "seconds", include_groups=False).reset_index())
    out = pd.concat([runs.assign(source="runs.csv"), e5.assign(experiment="E5", source="e5_timing.csv")
                     if len(e5) else None], ignore_index=True)
    out.to_csv(RES / "run_stats.csv", index=False)

    summ = (out.groupby("experiment", sort=False)
            .agg(configurations=("n", "size"), runs=("n", "sum"), median_iqr_pct=("iqr_pct", "median"),
                 p90_iqr_pct=("iqr_pct", lambda s: s.quantile(0.9)), max_iqr_pct=("iqr_pct", "max"),
                 over_10_pct=("iqr_pct", lambda s: int((s > 10).sum())))
            .reset_index())
    summ["configurations"] = summ.configurations.astype(int)
    summ["runs"] = summ.runs.astype(int)

    def widest(q, cols):
        w = q.sort_values("iqr_pct", ascending=False).head(10)[cols].copy()
        for c in ("n", "level"):
            if c in w:
                w[c] = w[c].astype(int)
        return w.fillna("")

    proc = widest(out[out.source == "runs.csv"], ["experiment", "dataset", "variant", "op", "method", "cache_state",
                                                  "n", "median_s", "q1_s", "q3_s", "iqr_pct"])
    inproc = widest(out[out.source == "e5_timing.csv"], ["dataset", "view", "level", "route", "cache", "n", "median_s",
                                                         "q1_s", "q3_s", "iqr_pct"]) if len(e5) else pd.DataFrame()
    lines = ["# Run statistics: median and IQR of every configuration", "",
             "Generated by `python -m bench.analysis.run_stats`. Every configuration with at least 3 measured runs; "
             "full list in `results/run_stats.csv` (median, quartiles, IQR, min, max). IQR % = (Q3 - Q1) / median. "
             "E1-E4: repeated runs of one configuration (process wall time). E5: in-process timings, spread over the "
             "8 tile positions (different places, so not only noise) or 3 whole-grid repeats.", "",
             "## Spread per experiment", "", md_table(summ, 1), "",
             "## E1-E4: the 10 widest spreads", "", md_table(proc, 3), "",
             "## E5: the 10 widest spreads (millisecond-scale tile timings)", "",
             md_table(inproc, 4) if len(inproc) else "(not run)", ""]
    (RES / "run_stats.md").write_text("\n".join(lines), encoding="utf-8")
    print(summ.to_string())
    print("wrote", RES / "run_stats.md", RES / "run_stats.csv")


if __name__ == "__main__":
    main()
