"""Full-grid correctness: our engine (Numba, float64, tiled) against gdaldem on the WHOLE 8 m and 2 m real grids,
for all 10 configurations of E1. The unit tests (tests/test_kernels.py) only use 1024 x 1024 crops.

For each grid and configuration: run gdaldem (default options) and the engine, compare window by window, delete
both outputs. Reported: cells compared, nodata-mask mismatches, max / mean |difference| over cells valid in both,
and the number of cells beyond the unit-test tolerance (TOL, same as tests/test_kernels.py). Aspect differences
are circular.
For Horn slope / aspect there is a second row, "parity": the NumPy reference with gdaldem's float32 neighbour sums
reproduced (gdal_rounding=True), with the tighter parity tolerance of the unit tests. It shows whether the
remaining differences of the float64 engine are only gdaldem's float32 rounding.
Writes results/e3_fullgrid_check.csv and .md.

    python -m tests.check_full_grid [grid ...]
"""
import csv
import subprocess
import sys
from pathlib import Path

import numpy as np
import rasterio
from rasterio.windows import Window

from bench.sweep import DATA, OUT_DIR
from demlab.engine import run
from demlab.io import read_with_halo, windows
from demlab.kernels import numpy_k
from tests.fixtures import OPS
from tests.test_kernels import TOL

GRIDS = {"tile571_8m": DATA / "prepared" / "tile571_8m.tif", "chamoli_2m": DATA / "prepared" / "chamoli_2m.tif"}
PARITY_TOL = {"slope": 1e-4, "aspect": 1e-3}  # as test_numpy_matches_gdaldem
RES = Path(__file__).resolve().parents[1] / "results"


def compare(op, ref_path, ours, tol):
    """ours(win) -> (array, nodata) for that window of the grid."""
    n = mask_diff = over = 0
    dmax, dsum = 0.0, 0.0
    with rasterio.open(ref_path) as r:
        rnd = r.nodata
        for row, col, h, w in windows(r.width, r.height, 2048):
            a = r.read(1, window=Window(col, row, w, h)).astype(np.float64)
            b, ond = ours((row, col, h, w))
            b = b.astype(np.float64)
            ra, ob = a == rnd, b == ond
            mask_diff += int(np.count_nonzero(ra != ob))
            m = ~ra & ~ob
            d = np.abs(a[m] - b[m])
            if op == "aspect":
                d = np.minimum(d, 360 - d)
            n += d.size
            if d.size:
                dmax = max(dmax, float(d.max()))
                dsum += float(d.sum())
                over += int(np.count_nonzero(d > tol))
    return {"cells_compared": n, "nodata_mask_mismatch": mask_diff, "max_abs_diff": dmax,
            "mean_abs_diff": dsum / max(n, 1), "cells_over_tol": over, "tol": tol}


def main(names):
    rows = []
    for name in names:
        src_path = GRIDS[name]
        for op, method in OPS:
            ref, out = OUT_DIR / "check_ref.tif", OUT_DIR / "check_ours.tif"
            cmd = ["gdaldem", op, str(src_path), str(ref), "-q"] + (["-alg", method] if method else [])
            subprocess.run(cmd, check=True)
            run(src_path, {op: str(out)}, backend="numba", method=method or "Horn")
            with rasterio.open(out) as o:
                def engine(win, o=o):
                    r, c, h, w = win
                    return o.read(1, window=Window(c, r, w, h)), o.nodata
                cases = [("engine (float64)", engine, TOL[op])]
                src = rasterio.open(src_path)
                if method == "Horn" and op in PARITY_TOL:
                    def parity(win, src=src, op=op):
                        z = read_with_halo(src, win, src.nodata)
                        return numpy_k.compute(op, z, src.res[0], "Horn", src.nodata, gdal_rounding=True), \
                            numpy_k.NODATA
                    cases.append(("parity (float32 sums)", parity, PARITY_TOL[op]))
                for label, fn, tol in cases:
                    r = {"grid": name, "op": op, "method": method, "version": label, **compare(op, ref, fn, tol)}
                    rows.append(r)
                    print(f"{name:11s} {op:9s} {method:17s} {label:22s} cells {r['cells_compared']:>11,}  mask "
                          f"mismatch {r['nodata_mask_mismatch']:>3}  max {r['max_abs_diff']:.2e}  mean "
                          f"{r['mean_abs_diff']:.1e}  over tol {r['cells_over_tol']:>6}", flush=True)
                src.close()
            ref.unlink()
            out.unlink()
    with open(RES / "e3_fullgrid_check.csv", "w", newline="") as f:
        wr = csv.DictWriter(f, fieldnames=list(rows[0]))
        wr.writeheader()
        wr.writerows(rows)
    lines = ["# Engine vs gdaldem on the full grids", "",
             "Generated by `python -m tests.check_full_grid`. Engine = Numba kernel, float64, 2048 windows; parity = "
             "NumPy reference with gdaldem's float32 Horn sums. Difference over cells valid in both outputs; "
             "aspect circular.", "",
             "| grid | op | method | version | cells compared | nodata mask mismatches | max abs diff | mean abs diff "
             "| tolerance | cells over tolerance | share over tolerance |", "|" + "---|" * 11]
    for r in rows:
        lines.append(f"| {r['grid']} | {r['op']} | {r['method']} | {r['version']} | {r['cells_compared']:,} | "
                     f"{r['nodata_mask_mismatch']:,} | {r['max_abs_diff']:.3g} | {r['mean_abs_diff']:.2g} | "
                     f"{r['tol']} | {r['cells_over_tol']:,} | {r['cells_over_tol'] / max(r['cells_compared'], 1):.2e} |")
    (RES / "e3_fullgrid_check.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", RES / "e3_fullgrid_check.md")


if __name__ == "__main__":
    main(sys.argv[1:] or list(GRIDS))
